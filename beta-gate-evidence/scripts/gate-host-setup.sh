#!/bin/bash
# R174: rebuild the local gate host from nothing (after the cloud container was replaced).
# Creates: test CA and gate.test certificate, Apache (HTTPS) with PHP-FPM, MariaDB database tegh_gate, the local SMTP
# sandbox, a private test config.php outside the web root with freshly generated secrets, and /srv/gate/t with the
# test scripts. Synthetic test host only: nothing here is a production secret, and none of it is committed.
set -e
REPO=/home/user/My-website; G=/srv/gate; EV=$REPO/beta-gate-evidence
mkdir -p $G/{www,t,pki,mail,ev/shots,backups} $G/sr-accountax-private/storage
grep -q gate.test /etc/hosts || echo "127.0.0.1 gate.test" >> /etc/hosts

# --- test CA and server certificate ---
# Issued with a start date of 1 January 2026: the gate pins the server clock back (clock-pin.sh), and a certificate
# issued "today" would not be valid yet on that clock, so emailed sign-in codes could not be sent over TLS.
if [ ! -f $G/pki/srv.crt ] || [ "$1" = renew-certs ]; then
  cd $G/pki
  OSSL="faketime 2026-01-01 openssl"
  $OSSL req -x509 -newkey rsa:2048 -nodes -days 825 -keyout ca.key -out ca.crt -subj "/CN=Tegh Gate Test CA" 2>/dev/null
  $OSSL req -newkey rsa:2048 -nodes -keyout srv.key -out srv.csr -subj "/CN=gate.test" 2>/dev/null
  printf 'subjectAltName=DNS:gate.test,DNS:localhost,IP:127.0.0.1\nextendedKeyUsage=serverAuth\n' > srv.ext
  $OSSL x509 -req -in srv.csr -CA ca.crt -CAkey ca.key -CAcreateserial -out srv.crt -days 825 -extfile srv.ext 2>/dev/null
  [ -f smtp.pw ] || head -c 18 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' > smtp.pw
  chmod 600 ca.key srv.key smtp.pw; chmod 644 srv.key   # Apache and the sandbox read the server key
fi
cp $G/pki/ca.crt /usr/local/share/ca-certificates/tegh-gate-ca.crt; update-ca-certificates >/dev/null 2>&1

# --- SMTP sandbox (STARTTLS + AUTH, writes each message to $G/mail) ---
cp $EV/scripts/smtp-sandbox.py $G/smtptls.py

# --- MariaDB ---
service mariadb start >/dev/null 2>&1 || true
DBPW_FILE=$G/sr-accountax-private/.dbpw
[ -f $DBPW_FILE ] || (head -c 18 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' > $DBPW_FILE; chmod 600 $DBPW_FILE)
mysql -e "CREATE DATABASE IF NOT EXISTS tegh_gate CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
 CREATE USER IF NOT EXISTS 'tegh_gate'@'localhost' IDENTIFIED BY '$(cat $DBPW_FILE)';
 ALTER USER 'tegh_gate'@'localhost' IDENTIFIED BY '$(cat $DBPW_FILE)';
 GRANT ALL PRIVILEGES ON tegh_gate.* TO 'tegh_gate'@'localhost'; FLUSH PRIVILEGES;"

