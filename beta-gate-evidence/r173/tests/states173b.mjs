import {createRequire} from 'module'; const {chromium} = createRequire('/opt/node22/lib/node_modules/')('playwright');
const b = await chromium.launch(); const out = process.argv[2]; const errs = [];
const page = async (w, h, scheme) => { const p = await b.newPage({viewport:{width:w,height:h}, colorScheme: scheme}); p.on('pageerror', e => errs.push(e.message.slice(0,120)));
  await p.route(/\/api\/index\.php/, r => r.fulfill({status: new URL(r.request().url()).searchParams.get('route')==='auth/security'?200:401, contentType:'application/json', body:'{"publicSignupEnabled":false}'})); return p; };
let p = await page(1440, 900, 'dark');
await p.goto('http://127.0.0.1:8174/app.html'); await p.waitForTimeout(1500);
await p.screenshot({path:`${out}/state-signin-dark.png`});
await p.click('#sr-choose-register'); await p.waitForTimeout(700);
await p.screenshot({path:`${out}/state-register-dark.png`});
await p.evaluate(() => { document.querySelectorAll('.sr-gate-form').forEach(f => f.hidden = true); const m = document.getElementById('sr-mfa-form'); m.hidden = false; m.querySelector('[data-mfa-email-hint]').textContent = 'o***@example.com'; });
await p.waitForTimeout(300); await p.screenshot({path:`${out}/state-mfa-dark.png`});
const colors = await p.evaluate(() => { const c = s => { const e = document.querySelector(s); return e ? getComputedStyle(e).color + ' on ' + getComputedStyle(e).backgroundColor : 'none'; }; return {panel: c('.sr-gate-panel'), input: c('#sr-mfa-form input[name=code]'), h2: c('#sr-mfa-form h2')}; });
console.log(JSON.stringify(colors));
await p.close();
p = await page(390, 844, 'light');
await p.goto('http://127.0.0.1:8174/product.html'); await p.waitForTimeout(1200);
await p.click('.mobile-toggle'); await p.waitForTimeout(500);
await p.screenshot({path:`${out}/state-mobile-menu.png`});
console.log('menu open:', await p.evaluate(() => getComputedStyle(document.querySelector('.mobile-nav')).display));
await p.keyboard.press('Escape'); await p.waitForTimeout(300);
console.log('menu after Escape:', await p.evaluate(() => getComputedStyle(document.querySelector('.mobile-nav')).display));
await p.close();
console.log(errs.join('\n') || 'no page errors'); await b.close();
